#!/usr/bin/env python3
"""Fill AcroForm fields from a UTF-8 JSON file; optionally flatten.

The JSON is a flat object: {"FieldName": "value", "Agree": true, ...}
- text fields: strings
- checkboxes: true/false (or an explicit on-state name like "/Yes")
- radio / dropdown: the export value as a string (see pdf_read.py --fields "options")

Regenerates supported field appearances and keeps NeedAppearances false so viewers
do not replace the generated appearance with a different font or checkbox style.
Flattening uses pypdf appearance merging; verify visually for exotic widgets.
"""
from __future__ import annotations

import argparse
import json
import sys
import os
import tempfile
from pathlib import Path


def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")
        except Exception:
            pass
    parser = argparse.ArgumentParser(description="Fill PDF AcroForm fields from JSON (pypdf).")
    parser.add_argument("pdf", help="Input form PDF")
    parser.add_argument("--fields-json", required=True, help="UTF-8 JSON file of field values")
    parser.add_argument("-o", "--output", required=True, help="Output PDF path")
    parser.add_argument("--flatten", action="store_true",
                        help="Merge all supported field appearances into pages and remove form widgets")
    parser.add_argument("--password", help="Password if the input is encrypted")
    args = parser.parse_args()

    try:
        from pypdf import PdfReader, PdfWriter
        from pypdf.generic import BooleanObject, NameObject
    except ImportError:
        print("Required Qubicl PDF dependency is unavailable: pypdf", file=sys.stderr)
        return 2

    with open(args.fields_json, encoding="utf-8") as fh:
        values = json.load(fh)

    if not isinstance(values, dict):
        raise ValueError("Field values must be a JSON object")

    reader = PdfReader(args.pdf)
    if reader.is_encrypted:
        if args.password is None or not reader.decrypt(args.password):
            print("Error: input is encrypted; pass --password", file=sys.stderr)
            return 3
    available = set((reader.get_fields() or {}).keys())
    missing = [name for name in values if name not in available]
    if missing:
        print(f"Warning: fields not found in form, skipped: {missing}", file=sys.stderr)

    writer = PdfWriter()
    writer.append(reader)

    # Normalize checkbox booleans to the field's actual on-state name
    # (e.g. "/Yes"): pypdf does not reliably map bare True to the on-state.
    field_info = reader.get_fields() or {}
    fill = {}
    for name, value in values.items():
        if name not in available:
            continue
        if isinstance(value, bool):
            states = [str(s) for s in (field_info[name].get("/_States_") or [])]
            on_state = next((s for s in states if s != "/Off"), "/Yes")
            value = on_state if value else "/Off"
        fill[name] = value
    for page in writer.pages:
        writer.update_page_form_field_values(page, fill, auto_regenerate=False)

    # Supported field appearances have already been regenerated by pypdf.
    root = writer._root_object
    if "/AcroForm" in root:
        root["/AcroForm"][NameObject("/NeedAppearances")] = BooleanObject(False)

    flattened = False
    if args.flatten:
        # Flatten every field, including untouched fields, before removing widgets.
        # Unsupported/signed widgets fail before writing rather than disappearing.
        all_values = {}
        for name, field in (writer.get_fields() or {}).items():
            kind = field.get("/FT")
            if kind is None and field.get("/Kids"):
                continue  # A nonterminal field group; its children carry values.
            if kind not in {"/Tx", "/Ch", "/Btn"}:
                raise ValueError(f"Cannot safely flatten unsupported field {name!r} ({kind})")
            all_values[name] = fill.get(name, field.get("/V", "/Off" if kind == "/Btn" else ""))
        for page in writer.pages:
            annotations = page.get("/Annots")
            if not annotations:
                continue
            visible = []
            for reference in annotations:
                annotation = reference.get_object()
                if annotation.get("/Subtype") != "/Widget":
                    visible.append(reference)
                    continue
                if "/FT" in annotation and "/T" in annotation:
                    parent = annotation
                else:
                    parent = annotation["/Parent"].get_object() if annotation.get("/Parent") else {}
                name = writer._get_qualified_field_name(parent=parent)
                if name not in all_values:
                    raise ValueError("Cannot safely flatten an unnamed or unsupported widget")
                # Invisible/Hidden/NoView widgets must not leak onto visible pages.
                if not int(annotation.get("/F", 0)) & (1 | 2 | 32):
                    visible.append(reference)
            from pypdf.generic import ArrayObject
            page[NameObject("/Annots")] = ArrayObject(visible)
            writer.update_page_form_field_values(page, all_values, auto_regenerate=False, flatten=True)
            page[NameObject("/Annots")] = annotations
        writer.remove_annotations("/Widget")
        root.pop("/AcroForm", None)
        if any(ref.get_object().get("/Subtype") == "/Widget" for page in writer.pages for ref in page.get("/Annots", [])):
            raise RuntimeError("Flattening left interactive widgets")
        flattened = True

    output = Path(args.output)
    with tempfile.NamedTemporaryFile(prefix=".qubicl-form-", dir=output.resolve().parent, delete=False) as fh:
        temporary = Path(fh.name)
        try:
            writer.write(fh)
        except BaseException:
            temporary.unlink(missing_ok=True)
            raise
    try:
        check = PdfReader(temporary)
        if args.flatten and check.get_fields():
            raise RuntimeError("Flattened output still contains fields")
        os.replace(temporary, output)
    finally:
        temporary.unlink(missing_ok=True)
    print(json.dumps({"output": args.output, "filled": sorted(fill), "skipped": missing,
                      "flattened": flattened}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
